INSERT INTO permissions(code) VALUES ('client.staff.assign.club_manager'), ('client.staff.revoke.club_manager'), ('client.club.reports.read');
CREATE TABLE client_manager_invitations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id BIGINT NOT NULL,
    club_id BIGINT NOT NULL,
    role_code VARCHAR(24) NOT NULL CHECK (role_code IN ('CLUB_MANAGER','NETWORK_MANAGER')),
    policy_version BIGINT NOT NULL CHECK (policy_version > 0),
    policy_hash VARCHAR(64) NOT NULL CHECK (CHAR_LENGTH(policy_hash)=64),
    inviter_user_id BIGINT NOT NULL REFERENCES users(id),
    issuer_ref VARCHAR(1024) NOT NULL,
    recipient_label VARCHAR(255) NOT NULL,
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    claimant_user_id BIGINT REFERENCES users(id),
    verification_code VARCHAR(8),
    claim_valid_until TIMESTAMP WITH TIME ZONE,
    source_id UUID UNIQUE REFERENCES client_role_assignments(id),
    status VARCHAR(8) NOT NULL DEFAULT 'issued' CHECK (status IN ('issued','claimed','accepted','revoked')),
    version BIGINT NOT NULL DEFAULT 1 CHECK (version > 0),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    UNIQUE (client_id,id),
    FOREIGN KEY(client_id,club_id) REFERENCES client_clubs(client_id,club_id),
    CHECK (status <> 'issued' OR claimant_user_id IS NULL),
    CHECK ((status='claimed' AND claimant_user_id IS NOT NULL AND verification_code IS NOT NULL AND claim_valid_until IS NOT NULL)
       OR (status<>'claimed' AND verification_code IS NULL)),
    CHECK ((status='accepted' AND source_id IS NOT NULL AND claimant_user_id IS NOT NULL)
       OR (status<>'accepted' AND source_id IS NULL))
);
CREATE INDEX idx_manager_invitation_scope ON client_manager_invitations(client_id,club_id,id);

-- A membership revocation fences all its clubs. A source revocation fences only its exact admission.
CREATE TABLE client_manager_invitation_fences (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    club_id BIGINT NULL,
    through_invitation_id BIGINT NOT NULL CHECK (through_invitation_id > 0),
    UNIQUE NULLS NOT DISTINCT (client_id,user_id,club_id,through_invitation_id),
    FOREIGN KEY (client_id,user_id) REFERENCES client_memberships(client_id,user_id) ON DELETE RESTRICT,
    FOREIGN KEY (client_id,club_id,user_id) REFERENCES client_club_access_state(client_id,club_id,user_id) ON DELETE RESTRICT,
    FOREIGN KEY (client_id,through_invitation_id) REFERENCES client_manager_invitations(client_id,id) ON DELETE RESTRICT
);
