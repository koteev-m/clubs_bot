ALTER TABLE client_memberships ADD COLUMN version BIGINT NOT NULL DEFAULT 1 CHECK (version > 0);

INSERT INTO permissions(code) VALUES ('client.application.manage');

CREATE TABLE client_membership_grants (
    client_id BIGINT NOT NULL CHECK (client_id > 0),
    user_id BIGINT NOT NULL CHECK (user_id > 0),
    permission_code VARCHAR(64) NOT NULL CHECK (permission_code = 'client.application.manage'),
    is_active BOOLEAN NOT NULL DEFAULT FALSE,
    version BIGINT NOT NULL DEFAULT 1 CHECK (version > 0),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY(client_id, user_id, permission_code),
    FOREIGN KEY(client_id, user_id) REFERENCES client_memberships(client_id, user_id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    FOREIGN KEY(permission_code) REFERENCES permissions(code) ON UPDATE RESTRICT ON DELETE RESTRICT
);

CREATE TABLE client_invitations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
    client_id BIGINT NOT NULL CHECK (client_id > 0),
    recipient_label VARCHAR(255) NOT NULL CHECK (char_length(trim(recipient_label)) BETWEEN 1 AND 255),
    token_hash VARCHAR(64) NOT NULL UNIQUE CHECK (char_length(token_hash) = 64),
    status VARCHAR(16) NOT NULL CHECK (status IN ('issued','claimed','accepted','revoked')),
    open_marker INTEGER NULL CHECK (open_marker = 1),
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    claimant_user_id BIGINT NULL,
    verification_code VARCHAR(8) NULL,
    claimed_at TIMESTAMP WITH TIME ZONE NULL,
    accepted_at TIMESTAMP WITH TIME ZONE NULL,
    revoked_at TIMESTAMP WITH TIME ZONE NULL,
    replaces_invitation_id BIGINT NULL UNIQUE,
    version BIGINT NOT NULL DEFAULT 1 CHECK (version > 0),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE(client_id, open_marker),
    UNIQUE(client_id, id),
    FOREIGN KEY(client_id) REFERENCES clients(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    FOREIGN KEY(claimant_user_id) REFERENCES users(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    FOREIGN KEY(client_id, replaces_invitation_id) REFERENCES client_invitations(client_id, id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CHECK (
        (status = 'issued' AND open_marker IS NOT NULL AND open_marker = 1 AND claimant_user_id IS NULL AND verification_code IS NULL
            AND claimed_at IS NULL AND accepted_at IS NULL AND revoked_at IS NULL)
        OR (status = 'claimed' AND open_marker IS NOT NULL AND open_marker = 1 AND claimant_user_id IS NOT NULL AND verification_code IS NOT NULL
            AND claimed_at IS NOT NULL AND accepted_at IS NULL AND revoked_at IS NULL)
        OR (status = 'accepted' AND open_marker IS NULL AND claimant_user_id IS NOT NULL AND verification_code IS NULL
            AND claimed_at IS NOT NULL AND accepted_at IS NOT NULL AND revoked_at IS NULL)
        OR (status = 'revoked' AND open_marker IS NULL AND verification_code IS NULL
            AND accepted_at IS NULL AND revoked_at IS NOT NULL)
    )
);
CREATE INDEX idx_client_invitations_claimant ON client_invitations(claimant_user_id, id);

CREATE TABLE client_club_applications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
    client_id BIGINT NOT NULL CHECK (client_id > 0),
    author_user_id BIGINT NOT NULL CHECK (author_user_id > 0),
    status VARCHAR(16) NOT NULL DEFAULT 'draft'
        CHECK (status IN ('draft','submitted','reviewing','approved','rejected','cancelled')),
    version BIGINT NOT NULL DEFAULT 1 CHECK (version > 0),
    venue_name VARCHAR(255) NOT NULL DEFAULT '',
    country_code VARCHAR(2) NOT NULL DEFAULT '',
    city VARCHAR(128) NOT NULL DEFAULT '',
    address VARCHAR(512) NOT NULL DEFAULT '',
    unit VARCHAR(128) NOT NULL DEFAULT '',
    timezone VARCHAR(64) NOT NULL DEFAULT '',
    comment VARCHAR(2000) NOT NULL DEFAULT '',
    previous_application_id BIGINT NULL,
    submitted_at TIMESTAMP WITH TIME ZONE NULL,
    submitted_snapshot TEXT NULL,
    submitted_hash VARCHAR(64) NULL,
    submitted_version BIGINT NULL CHECK (submitted_version > 0),
    approved_snapshot_hash VARCHAR(64) NULL,
    approved_snapshot_version BIGINT NULL CHECK (approved_snapshot_version > 0),
    venue_fingerprint VARCHAR(64) NULL,
    reserved_fingerprint VARCHAR(64) NULL,
    decision_reason VARCHAR(2000) NULL,
    internal_note VARCHAR(2000) NULL,
    commercial_reference VARCHAR(512) NULL,
    commercial_agreed_at DATE NULL,
    platform_confirmed BOOLEAN NOT NULL DEFAULT FALSE,
    decision_actor_user_id BIGINT NULL,
    decided_at TIMESTAMP WITH TIME ZONE NULL,
    history_json TEXT NOT NULL DEFAULT '[]',
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE(client_id, id),
    UNIQUE(id, client_id, author_user_id, status),
    UNIQUE(client_id, reserved_fingerprint),
    FOREIGN KEY(client_id, author_user_id) REFERENCES client_memberships(client_id, user_id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    FOREIGN KEY(client_id, previous_application_id) REFERENCES client_club_applications(client_id, id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    FOREIGN KEY(decision_actor_user_id) REFERENCES users(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CHECK ((status IN ('submitted','reviewing','approved') AND reserved_fingerprint IS NOT NULL
            AND reserved_fingerprint = venue_fingerprint)
        OR (status IN ('draft','rejected','cancelled') AND reserved_fingerprint IS NULL)),
    CHECK (status NOT IN ('submitted','reviewing','approved','rejected') OR
        (submitted_at IS NOT NULL AND submitted_snapshot IS NOT NULL AND submitted_hash IS NOT NULL
            AND venue_fingerprint IS NOT NULL AND submitted_version IS NOT NULL)),
    CHECK (status <> 'approved' OR (commercial_reference IS NOT NULL AND commercial_agreed_at IS NOT NULL
        AND platform_confirmed = TRUE AND decision_actor_user_id IS NOT NULL AND decided_at IS NOT NULL
        AND approved_snapshot_hash IS NOT NULL AND approved_snapshot_version IS NOT NULL
        AND approved_snapshot_hash = submitted_hash AND approved_snapshot_version = submitted_version)),
    CHECK (status <> 'rejected' OR (decision_reason IS NOT NULL AND char_length(trim(decision_reason)) > 0))
);
CREATE INDEX idx_client_applications_client_author ON client_club_applications(client_id, author_user_id, id);
CREATE INDEX idx_client_applications_queue ON client_club_applications(status, id);

CREATE TABLE client_commands (
    actor_user_id BIGINT NOT NULL CHECK (actor_user_id > 0),
    connection_key VARCHAR(64) NOT NULL,
    key_hash VARCHAR(64) NOT NULL CHECK (char_length(key_hash) = 64),
    request_hash VARCHAR(64) NOT NULL CHECK (char_length(request_hash) = 64),
    result_type VARCHAR(24) NOT NULL CHECK (result_type IN ('invitation','application','member')),
    result_id BIGINT NOT NULL CHECK (result_id > 0),
    client_id BIGINT NOT NULL CHECK (client_id > 0),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY(actor_user_id, connection_key, key_hash),
    FOREIGN KEY(actor_user_id) REFERENCES users(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    FOREIGN KEY(client_id) REFERENCES clients(id) ON UPDATE RESTRICT ON DELETE RESTRICT
);
