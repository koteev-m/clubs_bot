INSERT INTO booking_refund_reconciliation (
    booking_id,
    has_atomic_action_source,
    has_legacy_action_source,
    has_payment_status_source,
    blocked_reason
)
SELECT
    booking_id,
    FALSE,
    MAX(has_legacy_action_source),
    MAX(has_payment_status_source),
    CASE
        WHEN MAX(has_malformed_action) THEN 'MALFORMED_LEGACY_REFUND_ACTION'
        WHEN MAX(has_invalid_payment) THEN 'INVALID_REFUNDED_PAYMENT_AMOUNT'
        WHEN MAX(has_legacy_action_source) AND MAX(has_payment_status_source)
            THEN 'AMBIGUOUS_LEGACY_REFUND_SOURCES'
        ELSE NULL
    END
FROM (
    SELECT
        booking_id,
        COALESCE(refund_source_kind = 'LEGACY_ACTION', FALSE) AS has_legacy_action_source,
        FALSE AS has_payment_status_source,
        action = 'REFUND'
            AND status = 'OK'
            AND refund_fingerprint_version IS NULL
            AND refund_request_mode IS NULL
            AND refund_request_amount_minor IS NULL
            AND refund_result_amount_minor IS NULL AS has_malformed_action,
        FALSE AS has_invalid_payment
    FROM payment_actions
    UNION ALL
    SELECT
        booking_id,
        FALSE,
        status = 'REFUNDED' AND amount_minor > 0,
        FALSE,
        status = 'REFUNDED' AND amount_minor <= 0
    FROM payments
    WHERE booking_id IS NOT NULL
) reconciliation_sources
GROUP BY booking_id;
