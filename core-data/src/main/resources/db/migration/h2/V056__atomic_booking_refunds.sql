UPDATE payment_actions
SET refund_result_amount_minor = CAST(reason AS BIGINT),
    refund_source_kind = 'LEGACY_ACTION'
WHERE action = 'REFUND'
  AND status = 'OK'
  AND refund_fingerprint_version IS NULL
  AND refund_request_mode IS NULL
  AND refund_request_amount_minor IS NULL
  AND CASE
      WHEN reason ~ '^-?[0-9]{1,19}$'
          THEN CASE
              WHEN CAST(reason AS DECIMAL(20, 0)) <= 0 THEN FALSE
              ELSE CAST(reason AS DECIMAL(20, 0)) <= 9223372036854775807
          END
      ELSE FALSE
  END;

