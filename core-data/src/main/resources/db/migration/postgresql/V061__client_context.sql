-- Independent client authority. No legacy assignment or existing club is adopted automatically.
CREATE TABLE clients (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
    display_name VARCHAR(255) NOT NULL CHECK (char_length(trim(display_name)) BETWEEN 1 AND 255),
    is_active BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE client_memberships (
    client_id BIGINT NOT NULL CHECK (client_id > 0),
    user_id BIGINT NOT NULL CHECK (user_id > 0),
    is_active BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (client_id, user_id),
    FOREIGN KEY (client_id) REFERENCES clients(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    FOREIGN KEY (user_id) REFERENCES users(id) ON UPDATE RESTRICT ON DELETE CASCADE
);
CREATE INDEX idx_client_memberships_user_client ON client_memberships(user_id, client_id);

CREATE TABLE client_clubs (
    club_id BIGINT PRIMARY KEY CHECK (club_id > 0),
    client_id BIGINT NOT NULL CHECK (client_id > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (client_id, club_id),
    FOREIGN KEY (club_id) REFERENCES clubs(id) ON UPDATE RESTRICT ON DELETE CASCADE,
    FOREIGN KEY (client_id) REFERENCES clients(id) ON UPDATE RESTRICT ON DELETE RESTRICT
);

INSERT INTO permissions (code) VALUES ('client.club.read');

CREATE TABLE client_club_grants (
    client_id BIGINT NOT NULL CHECK (client_id > 0),
    user_id BIGINT NOT NULL CHECK (user_id > 0),
    club_id BIGINT NOT NULL CHECK (club_id > 0),
    permission_code TEXT NOT NULL CHECK (permission_code = 'client.club.read'),
    is_active BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (client_id, user_id, club_id, permission_code),
    FOREIGN KEY (client_id, user_id) REFERENCES client_memberships(client_id, user_id)
        ON UPDATE RESTRICT ON DELETE CASCADE,
    FOREIGN KEY (client_id, club_id) REFERENCES client_clubs(client_id, club_id)
        ON UPDATE RESTRICT ON DELETE CASCADE,
    FOREIGN KEY (permission_code) REFERENCES permissions(code) ON UPDATE RESTRICT ON DELETE RESTRICT
);
CREATE INDEX idx_client_club_grants_user_client_club ON client_club_grants(user_id, client_id, club_id);
