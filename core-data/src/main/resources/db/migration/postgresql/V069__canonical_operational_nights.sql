-- Cabinet canonical identity. Legacy events and their foreign keys keep their current lifecycle.
CREATE TABLE club_operational_nights (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id BIGINT NOT NULL,
    club_id BIGINT NOT NULL,
    business_date DATE NOT NULL,
    timezone VARCHAR(100) NOT NULL,
    start_at TIMESTAMP WITH TIME ZONE NOT NULL,
    end_at TIMESTAMP WITH TIME ZONE NOT NULL,
    source VARCHAR(20) NOT NULL CHECK (source IN ('WEEKEND_RULE', 'HOLIDAY', 'EXCEPTION')),
    status VARCHAR(12) NOT NULL CHECK (status IN ('SCHEDULED', 'CANCELLED')),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_club_operational_nights_date UNIQUE (club_id, business_date),
    CONSTRAINT ck_club_operational_nights_window CHECK (end_at > start_at),
    FOREIGN KEY (client_id, club_id) REFERENCES client_clubs(client_id, club_id)
        ON UPDATE RESTRICT ON DELETE RESTRICT
);
